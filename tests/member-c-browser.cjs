// 运行：node tests/member-c-browser.cjs <包含 playwright 的 node_modules 绝对路径>
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const os=require('node:os');
const {pathToFileURL}=require('node:url');
const {chromium}=require(path.join(process.argv[2],'playwright'));
const Zip=require('../assets/vendor/jszip.min.js');
const output=fs.mkdtempSync(path.join(os.tmpdir(),'member-c-qa-'));
(async()=>{
  const browser=await chromium.launch({channel:'msedge',headless:true});
  try{
    const context=await browser.newContext({acceptDownloads:true,viewport:{width:1440,height:1000}});
    const page=await context.newPage(),errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    const url=name=>pathToFileURL(path.join(__dirname,'..',name+'.html')).href;
    await page.goto(url('review'));
    await page.evaluate(()=>{localStorage.clear();localStorage.setItem('demoRole','arbitrator');});
    await page.reload();
    await page.getByRole('button',{name:'提交最终版本',exact:true}).waitFor();
    assert.equal(await page.locator('article').count(),3);
    assert.equal(await page.getByRole('button',{name:'提交最终版本',exact:true}).isDisabled(),true);
    const rows=page.locator('article');
    await rows.nth(0).getByText('采纳 B',{exact:true}).click();
    await rows.nth(1).getByText('手动重标',{exact:true}).click();
    await page.getByRole('dialog').waitFor();
    await page.getByRole('spinbutton').nth(1).fill('37');
    await page.getByRole('button',{name:'应用重标',exact:true}).click();
    await rows.nth(2).getByText('采纳 A',{exact:true}).click();
    await rows.nth(0).getByPlaceholder('裁定理由 / 需要专家讨论的问题（可选）').fill('核对合同条款');
    await rows.nth(2).getByRole('button',{name:'标记待专家裁决',exact:true}).click();
    assert.equal(await page.getByRole('button',{name:'提交最终版本',exact:true}).isDisabled(),true);
    await rows.nth(2).getByRole('button',{name:'取消专家裁决',exact:true}).click();
    await page.getByRole('button',{name:'保存草稿',exact:true}).click();
    await page.reload();
    const stored=await page.evaluate(()=>JSON.parse(localStorage.getItem('nju.memberC.v1')));
    assert.equal(stored.decisions['label:P2'].pick,'B');
    assert.equal(stored.decisions['boundary:P3'].custom.end,37);
    await page.getByRole('button',{name:'差异比对',exact:true}).click();
    await page.waitForURL('**/compare.html');
    assert.equal(await page.locator('article').count(),3);
    assert.equal(await page.locator('article').filter({hasText:'已处理'}).count(),3);
    await page.locator('article').first().getByRole('button',{name:'查看 / 处理此争议'}).click();
    await page.waitForURL('**/review.html?focus=*');
    await page.getByRole('button',{name:'提交最终版本',exact:true}).click();
    await page.getByRole('button',{name:'确认定稿',exact:true}).click();
    await page.getByRole('button',{name:'进入结果输出',exact:true}).waitFor();
    assert.equal(await page.getByRole('button',{name:'保存草稿',exact:true}).isDisabled(),true);
    await page.getByRole('button',{name:'进入结果输出',exact:true}).click();
    await page.waitForURL('**/results.html');
    await page.locator('.c-graph').waitFor();
    await page.getByText('论证图示 PNG',{exact:true}).click();
    await page.getByText('论证图示 SVG',{exact:true}).click();
    await page.locator('input[type=file]').nth(1).setInputFiles({name:'指南.txt',mimeType:'text/plain',buffer:Buffer.from('真实测试指南')});
    const downloadEvent=page.waitForEvent('download');
    await page.getByRole('button',{name:'生成压缩包并下载',exact:true}).click();
    const download=await downloadEvent;
    const zipPath=path.join(output,download.suggestedFilename());await download.saveAs(zipPath);
    const zip=await Zip.loadAsync(fs.readFileSync(zipPath),{checkCRC32:true});
    assert.ok(zip.file('argument.png')); assert.ok(zip.file('argument.svg'));assert.ok(zip.file('annotations.xlsx'));
    const png=await zip.file('argument.png').async('nodebuffer');
    assert.equal(png.subarray(0,8).toString('hex'),'89504e470d0a1a0a');
    assert.equal(await zip.file('guide/指南.txt').async('string'),'真实测试指南');
    const json=JSON.parse(await zip.file('annotations.json').async('string'));
    assert.equal(json.propositions[1].tag1,'GM');assert.equal(json.propositions[2].text,'被告应向原告支付该款项。');
    fs.writeFileSync(path.join(output,'annotations.xlsx'),await zip.file('annotations.xlsx').async('nodebuffer'));
    fs.writeFileSync(path.join(output,'argument.svg'),await zip.file('argument.svg').async('nodebuffer'));
    fs.writeFileSync(path.join(output,'argument.png'),png);
    const another=await page.evaluate(()=>JSON.parse(localStorage.getItem('nju.memberC.v1')));
    another.dataset.task.name='另一指南版本任务';another.dataset.task.guideVersion='v2.0';
    await page.locator('input[type=file]').first().setInputFiles({name:'another.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(another))});
    await page.getByRole('button',{name:'导入',exact:true}).last().click();
    await page.getByText('任务：另一指南版本任务',{exact:true}).waitFor();
    assert.equal(await page.getByText('尚未选择附件',{exact:true}).count(),1,'切换任务不能继续沿用上一任务的指南附件');
    await page.reload();
    assert.equal(await page.locator('.el-table__body-wrapper').last().locator('tbody tr').count(),1);
    await page.screenshot({path:path.join(output,'results.png'),fullPage:true,animations:'disabled'});
    await page.goto(url('review'));
    await page.screenshot({path:path.join(output,'review.png'),fullPage:true,animations:'disabled'});
    assert.equal(await page.getByRole('button',{name:'提交最终版本',exact:true}).isDisabled(),true);
    const finalBackup=await page.evaluate(()=>JSON.parse(localStorage.getItem('nju.memberC.v1')));
    await page.locator('input[type=file]').first().setInputFiles({name:'invalid.json',mimeType:'application/json',buffer:Buffer.from('{"schemaVersion":1}')});
    await page.getByText('缺少任务 ID 或名称',{exact:true}).waitFor();
    assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('nju.memberC.v1')).stage),'final');
    for(const name of ['第二次对照','第三次对照']){
      const ds=structuredClone(finalBackup.dataset);ds.task.name=name;
      await page.locator('input[type=file]').first().setInputFiles({name:'new.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(ds))});
      await page.getByRole('button',{name:'导入',exact:true}).last().click();
      await page.getByText('任务：'+name,{exact:true}).waitFor();
    }
    assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('nju.memberC.archives.v1')).some(s=>s.stage==='final')),true,'同任务 ID 的新版本不能丢失先前的只读版本');
    await page.evaluate(()=>localStorage.setItem('nju.memberC.archives.v1','{bad'));
    await page.reload();
    await page.locator('.el-alert--error').waitFor();
    await page.locator('input[type=file]').first().setInputFiles({name:'backup.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(finalBackup))});
    await page.getByRole('button',{name:'导入',exact:true}).last().click();
    await page.getByRole('button',{name:'进入结果输出',exact:true}).waitFor();
    await page.reload();
    assert.equal(await page.locator('.el-alert--error').count(),0,'恢复数据后刷新不应再次出现存档损坏错误');
    const preserved=[finalBackup];
    await page.evaluate(s=>{localStorage.setItem('nju.memberC.archives.v1',JSON.stringify(s));localStorage.setItem('nju.memberC.v1','{bad');},preserved);
    await page.reload();
    await page.locator('.el-alert--error').waitFor();
    await page.locator('input[type=file]').first().setInputFiles({name:'backup.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(finalBackup))});
    await page.getByRole('button',{name:'导入',exact:true}).last().click();
    await page.getByRole('button',{name:'进入结果输出',exact:true}).waitFor();
    assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('nju.memberC.archives.v1')).length),1,'当前任务损坏不能连带清空有效存档');
    await page.getByRole('button',{name:'进入结果输出',exact:true}).click();
    await page.waitForURL('**/results.html');
    await page.locator('.topbar .el-select').click();
    await page.getByRole('option',{name:'标注员',exact:true}).click();
    assert.equal(await page.getByRole('button',{name:'生成压缩包并下载',exact:true}).isDisabled(),true);
    await page.locator('.topbar .el-select').click();
    await page.getByRole('option',{name:'任务创建者',exact:true}).click();
    assert.equal(await page.getByRole('button',{name:'生成压缩包并下载',exact:true}).isDisabled(),false);
    await page.goto(url('compare'));
    await page.getByPlaceholder('搜索命题、关系或原文').fill('R1');
    assert.equal(await page.locator('article').count(),1);
    assert.deepEqual(errors,[]);
    console.log('PASS：裁定、重标、专家待办、草稿刷新、跨页比对、只读定稿、四格式压缩包、指南附件、导出记录、非法导入、同任务版本存档、损坏数据恢复、浏览器无异常。');
    console.log('QA_OUTPUT='+output);
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
